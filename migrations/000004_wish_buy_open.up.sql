-- 心愿商城：是否开放购买（临时开关）
--
-- 淘宝 / 京东那条外链有时候会失效（商品下架、店铺关了、链接被改）。
-- 运营需要**临时**把「去购买」关掉，而商品本身照旧在列表里
-- （孩子还能许愿，家长自己买完还能回来点「已经买好了」收尾）。
--
--   buy_open = 1（默认）→ 配了 buy_url 就下发，两端都有「去购买」
--   buy_open = 0        → 不下发外链 ⇒ 按钮消失，商品仍在架
--
-- ⚠️ 和 archived（下架）不是一回事：下架是把商品整个藏起来。
-- ⚠️ DEFAULT 1 不能省：加列那一刻的存量行必须读成「开」，
--    否则全站「去购买」一起消失，而且不报错。
ALTER TABLE wish_item ADD COLUMN buy_open INTEGER NOT NULL DEFAULT 1;
